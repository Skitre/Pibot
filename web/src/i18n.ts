export type MessageKey = keyof typeof zh;

const dict: Record<Locale, Record<MessageKey, string>> = { zh, en };

function fill(s: string, vars?: Vars): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

export function t(key: MessageKey, vars?: Vars, locale: Locale = prefs.get().locale): string {
  return fill(dict[locale][key] ?? zh[key], vars);
}

export type TFn = (key: MessageKey, vars?: Vars) => string;

export function useT(): TFn {
  const { locale } = usePrefs();
  return (key, vars) => t(key, vars, locale);
}

