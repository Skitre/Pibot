export function translateToolName(name: string, tr: TFn = t): string {
  const mcp = /^mcp[_:]{1,2}(.+?)[_:]{1,2}(.+)$/.exec(name);
  if (mcp) return `${mcp[2]} · ${mcp[1]}`;
  const key = TOOL_KEYS[name];
  return key ? tr(key) : name;
}

